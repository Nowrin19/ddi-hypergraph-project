def infer_embedding_matrix(df: pd.DataFrame):
    if 'DrugBank_ID' not in df.columns:
        raise ValueError("Embeddings CSV must contain 'DrugBank_ID'.")

    ids = df['DrugBank_ID'].astype(str).tolist()

    embedding_col = None
    for candidate in ['embedding', 'embeddings', 'vector', 'embed', 'emb']:
        if candidate in df.columns:
            embedding_col = candidate
            break

    if embedding_col is not None:
        sample = df[embedding_col].dropna().iloc[0]
        if isinstance(sample, str):
            emb_list = df[embedding_col].apply(lambda x: ast.literal_eval(x) if isinstance(x, str) else x)
            emb = np.vstack(emb_list.values).astype(np.float32)
        else:
            emb = np.vstack(df[embedding_col].values).astype(np.float32)
    else:
        num_df = df.drop(columns=['DrugBank_ID']).select_dtypes(include=[np.number])
        emb = num_df.values.astype(np.float32)

    return ids, emb

def build_hypergraph_from_embeddings(ids, emb, k=10, sim_threshold=0.0):
    emb_norm = sk_normalize(emb, axis=1)
    sim = cosine_similarity(emb_norm)
    np.fill_diagonal(sim, 0.0)

    hyperedges = {}
    for i in range(len(ids)):
        top_idx = np.argsort(sim[i])[-(k+1):]
        members = [ids[j] for j in top_idx]
        hyperedges[f"he_knn_{i}"] = set(members)

    if sim_threshold > 0.0:
        G = nx.Graph()
        G.add_nodes_from(ids)
        rows, cols = np.where(sim > sim_threshold)
        for a, b in zip(rows, cols):
            if a < b:
                G.add_edge(ids[a], ids[b])
        comps = [list(c) for c in nx.connected_components(G) if len(c) >= 3]
        for ci, comp in enumerate(comps):
            hyperedges[f"he_comp_{ci}"] = set(comp)

    H = hnx.Hypergraph(hyperedges)
    return H, hyperedges

def incidence_matrix(H: hnx.Hypergraph, hyperedges: dict, ids: list, device: torch.device):
    node_index = {n: i for i, n in enumerate(ids)}
    Hm = torch.zeros((len(ids), len(H.edges)), dtype=torch.float32, device=device)
    for j, he in enumerate(H.edges):
        members = hyperedges[he]
        for nname in members:
            if nname in node_index:
                Hm[node_index[nname], j] = 1.0
    return Hm

