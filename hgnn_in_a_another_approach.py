class SimpleHGNN(nn.Module):
    def __init__(self, in_dim, hidden_dim=128, out_dim=128):
        super().__init__()
        self.fc = nn.Linear(in_dim, hidden_dim)
        self.proj = nn.Linear(hidden_dim, out_dim)

    def forward(self, x, H):
        dv = H.sum(dim=1).clamp(min=1.0)
        de = H.sum(dim=0).clamp(min=1.0)
        Dv_inv_sqrt = dv.pow(-0.5).unsqueeze(1)
        De_inv = de.pow(-1.0).unsqueeze(1)

        y = Dv_inv_sqrt * x
        y = H.t() @ y
        y = De_inv * y
        y = H @ y
        y = Dv_inv_sqrt * y

        h = F.relu(self.fc(y))
        z = self.proj(h)
        return z

class PairMLP(nn.Module):
    def __init__(self, dim, hidden=128):
        super().__init__()
        self.mlp = nn.Sequential(
            nn.Linear(dim*4, hidden),
            nn.ReLU(),
            nn.Linear(hidden, 1)
        )

    def forward(self, zi, zj):
        feats = torch.cat([zi, zj, torch.abs(zi - zj), zi * zj], dim=-1)
        return self.mlp(feats).squeeze(-1)

