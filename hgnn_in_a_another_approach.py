def evaluate(z, pairs, labels, id2idx, decoder, device):
    zi, zj, new_labels = [], [], []

    for (d1, d2), lbl in zip(pairs, labels):
        if d1 not in id2idx or d2 not in id2idx:
            continue
        zi.append(z[id2idx[d1]].unsqueeze(0))
        zj.append(z[id2idx[d2]].unsqueeze(0))
        new_labels.append(lbl)

    if len(zi) == 0:  # edge case
        return 0, 0, 0, 0, []

    zi = torch.cat(zi, dim=0).to(device)
    zj = torch.cat(zj, dim=0).to(device)
    labels = torch.tensor(new_labels, dtype=torch.float, device=device)

    with torch.no_grad():
        preds = decoder(zi, zj)

    # turn preds into probabilities
    probs = torch.sigmoid(preds).cpu().numpy()
    labels = labels.cpu().numpy()

    # compute metrics
    from sklearn.metrics import roc_auc_score, average_precision_score, accuracy_score, f1_score

    auc = roc_auc_score(labels, probs)
    aupr = average_precision_score(labels, probs)
    acc = accuracy_score(labels, (probs > 0.5).astype(int))
    f1 = f1_score(labels, (probs > 0.5).astype(int))

    return auc, aupr, acc, f1, probs




